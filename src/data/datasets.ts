export function getCatalogStats(items: Dataset[] = datasets): CatalogStats {
  const sevenDaysAgo = Date.now() - 7 * 24 * 60 * 60 * 1000;
  const pending = items.reduce(
    (sum, d) => sum + d.pendingRequests.length,
    0
  );

  return {
    totalDatasets: items.length,
    pendingAccessRequests: pending,
    piiDatasets: items.filter((d) => d.containsPii).length,
    averageQualityScore:
      items.reduce((sum, d) => sum + d.quality.score, 0) / items.length,
    recentlyUpdated: items.filter(
      (d) => new Date(d.updatedAt).getTime() >= sevenDaysAgo
    ).length,
  };
}

