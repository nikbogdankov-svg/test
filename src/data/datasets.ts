function usageBase(
  accesses: number,
  consumers: { name: string; type: "team" | "user" | "ai"; count: number }[],
  assistants: { name: string; queries: number; lastUsed: string }[],
  queries: {
    id: string;
    query: string;
    user: string;
    timestamp: string;
    durationMs: number;
  }[]
) {
  const trend = Array.from({ length: 14 }, (_, i) => {
    const day = new Date("2026-07-28T00:00:00Z");
    day.setDate(day.getDate() - (13 - i));
    return {
      date: day.toISOString().slice(0, 10),
      count: Math.max(
        4,
        Math.round(accesses / 30 + Math.sin(i / 2) * 12 + (i % 3) * 5)
      ),
    };
  });

  return {
    accessesLast30Days: accesses,
    accessTrend: trend,
    topConsumers: consumers,
    aiAssistants: assistants,
    recentQueries: queries,
  };
}

